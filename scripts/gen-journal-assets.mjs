import fs from 'node:fs/promises';
import {packResource} from './journal-pack-resource.mjs';
import { build } from 'esbuild';

// Retain the Unicode data notice; ambiguous and private-use entries stay reviewable.
const symbolData=await fs.readFile('assets/journal/adobe-symbol.txt','utf8'),symbolCandidates=new Map();
for(const line of symbolData.split(/\r?\n/)){
  const match=line.match(/^([0-9A-F]+)\s+([0-9A-F]+)/);if(!match)continue;
  const unicode=parseInt(match[1],16),code=parseInt(match[2],16);
  if(unicode>=0xE000&&unicode<=0xF8FF)continue;
  const values=symbolCandidates.get(code)??[];values.push(unicode);symbolCandidates.set(code,values);
}
const symbolMap=Object.fromEntries([...symbolCandidates].filter(([,v])=>v.length===1).map(([k,v])=>[k,String.fromCodePoint(v[0])]));
const symbolNotice=symbolData.split(/\r?\n/).filter(l=>l.startsWith('#')).join('\n').replaceAll('*/','* /');
await fs.writeFile('src/journal/symbolMapping.generated.ts',`/* Generated from assets/journal/adobe-symbol.txt.\n${symbolNotice}\n*/\nexport const SYMBOL_MAP:Readonly<Record<number,string>>=${JSON.stringify(symbolMap,null,2)};\n`);

const path='node_modules/@myriaddreamin/typst-ts-web-compiler/pkg/typst_ts_web_compiler_bg.wasm';
const wasm=await fs.readFile(path);
const result=await build({entryPoints:['src/journal/engine.worker.ts'],bundle:true,write:false,platform:'browser',format:'iife',target:'es2022',minify:true,plugins:[{
  name:'journal-browser-wasm-boundary',setup(builder){
    builder.onLoad({filter:/typst_ts_web_compiler\.mjs$/},async args=>{
      let contents=await fs.readFile(args.path,'utf8');
      let callbacks=0;
      contents=contents.replace(/const ret = new Function\([^;]+;\s*return addHeapObject\(ret\);/g,()=>{callbacks++;return `const body = getStringFromWasm0(arg0,arg1);
        const second = typeof arg2 === "number" ? getStringFromWasm0(arg2,arg3) : "";
        if (!second && body === "return 0") return addHeapObject(function(){return 0;});
        if (!second && body === "return true") return addHeapObject(function(){return true;});
        if (!second && (body === "return this" || body === "return this;")) return addHeapObject(function(){return globalThis;});
        if (body === "path" && second === "return path") return addHeapObject(function(path){return path;});
        if (!second && body === "throw new Error('Dummy AccessModel, please initialize compiler with withAccessModel()')") return addHeapObject(function(){throw new Error("Journal access model must be initialized");});
        if (!second && body === "throw new Error('Dummy Registry, please initialize compiler with withPackageRegistry()')") return addHeapObject(function(){throw new Error("External Typst packages are disabled");});
        throw new Error("Unsupported static WASM callback: "+body.slice(0,160)+" | "+second.slice(0,160));`;});
      if(callbacks!==2)throw new Error(`Unreviewed Typst WASM binding: ${callbacks} dynamic callbacks`);
      contents=contents.replace("module_or_path = importWasmModule('typst_ts_web_compiler_bg.wasm', import.meta.url);",'throw new Error("Explicit embedded WASM bytes are required");');
      return {contents,loader:'js'};
    });
  }
}]});
// Rename the binding's diagnostic string to avoid mistaking it for executable
// Function construction in the independent final-bundle lexical guard.
const worker=result.outputFiles[0].text.replaceAll('`Function(${', '`Callable(${');
if(/new Function|\beval\s*\(|node:fs|import\(/.test(worker))throw new Error('Unsafe journal worker');
const packed=await packResource(wasm);
const packedWorker=await packResource(Buffer.from(worker,'utf8'));
const brand=Object.fromEntries(await Promise.all(["crossmark.svg"].map(async name=>[name,await fs.readFile("assets/journal/"+name,"utf8")])));
await fs.writeFile('src/journal/embedded.generated.ts',`// Generated by gen-journal-assets.mjs. Never fetch code at runtime.\nexport const JOURNAL_WORKER_RESOURCE = ${JSON.stringify(packedWorker)} as const;\nexport const JOURNAL_WASM_RESOURCE = ${JSON.stringify(packed)} as const;\n`);
console.log(`Journal: ${wasm.length} WASM bytes, ${packed.data.length} embedded, ${worker.length} worker chars`);
await fs.appendFile("src/journal/embedded.generated.ts",`export const JOURNAL_BRAND_ASSETS: Record<string,string> = ${JSON.stringify(brand)};\n`);
